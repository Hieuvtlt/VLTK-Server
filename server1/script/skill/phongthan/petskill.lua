-----------------------------------------------------------
--函数GetSkillLevelData(levelname, data, level)
--levelname：魔法属性名称
--data：技能名称
--level：技能等级
--return：当技能名称为data，技能等级为level
--			时的魔法属性levelname所需求的三个参数的具体值
-----------------------------------------------------------
function GetSkillLevelData(levelname, data, level)
	local gf_Is4Faction = 1 -- 0 la 3 phai, 1 la 4 phai
	if gf_Is4Faction == 1 then
		if(data==nil) then
			return ""
		end
		if(data == "") then
			return ""
		end
		if(SKILLS_4P[data]==nil) then
			return ""
		end
		if(SKILLS_4P[data][levelname]==nil) then
			return ""
		end
		if(type(SKILLS_4P[data][levelname]) == "function") then
			return SKILLS_4P[data][levelname](level)
		end
		if(SKILLS_4P[data][levelname][1]==nil) then
			SKILLS_4P[data][levelname][1]={{0,0},{20,0}}
		end
		if(SKILLS_4P[data][levelname][2]==nil) then
			SKILLS_4P[data][levelname][2]={{0,0},{20,0}}
		end
		if(SKILLS_4P[data][levelname][3]==nil) then
			SKILLS_4P[data][levelname][3]={{0,0},{20,0}}
		end
		p1=floor(Link(level,SKILLS_4P[data][levelname][1]))
		p2=floor(Link(level,SKILLS_4P[data][levelname][2]))
		p3=floor(Link(level,SKILLS_4P[data][levelname][3]))
		return Param2String(p1,p2,p3)
	else
		if(data==nil) then
			return ""
		end
		if(data == "") then
			return ""
		end
		if(SKILLS[data]==nil) then
			return ""
		end
		if(SKILLS[data][levelname]==nil) then
			return ""
		end
		if(type(SKILLS[data][levelname]) == "function") then
			return SKILLS[data][levelname](level)
		end
		if(SKILLS[data][levelname][1]==nil) then
			SKILLS[data][levelname][1]={{0,0},{20,0}}
		end
		if(SKILLS[data][levelname][2]==nil) then
			SKILLS[data][levelname][2]={{0,0},{20,0}}
		end
		if(SKILLS[data][levelname][3]==nil) then
			SKILLS[data][levelname][3]={{0,0},{20,0}}
		end
		p1=floor(Link(level,SKILLS[data][levelname][1]))
		p2=floor(Link(level,SKILLS[data][levelname][2]))
		p3=floor(Link(level,SKILLS[data][levelname][3]))
		return Param2String(p1,p2,p3)
	end
end


function Param2String(Param1, Param2, Param3)
return Param1..","..Param2..","..Param3
end
